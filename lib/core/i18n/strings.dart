import '../../app/app_settings.dart';

/// Translate [key] into the currently selected app language.
/// Falls back to Tajik, then to the key itself.
///
/// Pass [params] to fill placeholders written as `{name}` in the string:
///
///     tr('story.replyTo', {'user': 'ali'})   // "ali-га ҷавоб..."
///
/// Word order differs between languages, so a sentence built by
/// concatenating pieces in Dart cannot be translated — the placeholder
/// has to live inside the translated string, where each language can
/// put it where that language needs it.
String tr(String key, [Map<String, Object?>? params]) {
  final lang = AppSettingsState.instance.lang;
  final table = _strings[lang] ?? _strings['tj']!;
  var out = table[key] ?? _strings['tj']?[key] ?? key;
  if (params != null) {
    params.forEach((k, v) => out = out.replaceAll('{$k}', '${v ?? ''}'));
  }
  return out;
}

/// Plural helper: picks `<key>.one` for 1 and `<key>.many` otherwise,
/// and fills `{n}` with the count.
///
/// Tajik and English agree on one-vs-many here; Russian has a third
/// form for 2–4, so `<key>.few` is used when the table provides it.
String trn(String key, int n) {
  final lang = AppSettingsState.instance.lang;
  final table = _strings[lang] ?? _strings['tj']!;
  String suffix;
  if (lang == 'ru') {
    suffix = _ruSuffix(n, table.containsKey('$key.few'));
  } else {
    suffix = n == 1 ? '.one' : '.many';
  }
  return tr('$key$suffix', {'n': n});
}

/// Russian plural form for [n].
///
/// The form follows the last digit, not the whole number: 21 takes the
/// singular ("21 участник") and 22–24 take the "few" form, while the
/// teens 11–14 are the exception and all take the "many" form.
String _ruSuffix(int n, bool hasFew) {
  final mod100 = n.abs() % 100;
  if (mod100 >= 11 && mod100 <= 14) return '.many';
  final mod10 = n.abs() % 10;
  if (mod10 == 1) return '.one';
  if (mod10 >= 2 && mod10 <= 4 && hasFew) return '.few';
  return '.many';
}

