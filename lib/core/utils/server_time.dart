//  Вақти сервер → вақти ТЕЛЕФОНИ корбар.
//
//  ⚠️ Чаро ин лозим шуд.
//
//  Вақт дар барнома хато нишон дода мешуд. Ду сабаб:
//
//  1. Ҳар экран худаш ҳисоб мекард. Танҳо ЯК ҷо `.toLocal()` дошт,
//     боқӣ не. Пас як пост дар лента як вақт, дар профил вақти
//     дигар нишон медод.
//
//  2. Агар сатри вақт минтақаро надошта бошад («2026-09-19T05:33:06»
//     бе `Z`), Dart онро МАҲАЛЛӢ мешуморад. Вале сервер ҳамеша дар
//     UTC менависад. Дар Тоҷикистон ин фарқи ПАНҶ СОАТ медиҳад:
//     пости навро «5 соат пеш» нишон медод.
//
//  Ҳалли реша: як ҷои таҷзия барои тамоми барнома. Ҳар модел
//  ҳаминро истифода мебарад — пас фаромӯш кардан имконнопазир аст.
// ══════════════════════════════════════════════════════════════════

/// Сатри вақти серверро ба вақти МАҲАЛЛИИ телефон табдил медиҳад.
///
/// Қабул мекунад: `2026-09-19T05:33:06Z`, `...+05:00`, ё бе минтақа.
/// Сатри бе минтақа ҳамчун UTC хонда мешавад, чунки сервер ҳамеша
/// дар UTC менависад.
///
/// Барои вуруди вайрон `null` бармегардад — на вақти ҷорӣ. Вақти
/// ҷорӣ дурӯғ мебуд: «ҳозир» ба ҷои «номаълум».
DateTime? parseServerTime(dynamic raw) {
  if (raw == null) return null;
  if (raw is DateTime) return raw.toLocal();

  var s = raw.toString().trim();
  if (s.isEmpty) return null;

  // Postgres баъзан бо фосила менависад, на бо «T».
  if (s.length > 10 && s[10] == ' ') {
    s = '${s.substring(0, 10)}T${s.substring(11)}';
  }

  final hasZone = s.endsWith('Z') ||
      s.endsWith('z') ||
      RegExp(r'[+-]\d{2}:?\d{2}$').hasMatch(s);

  final parsed = DateTime.tryParse(hasZone ? s : '${s}Z');
  return parsed?.toLocal();
}

/// Фарқи вақт аз ҲОЗИР, аз рӯи соати ТЕЛЕФОН.
///
/// Соати телефон метавонад аз сервер каме пеш бошад. Он гоҳ фарқ
/// манфӣ мешавад ва «пас аз 3 соат» нишон дода мешуд. Фарқи манфӣ
/// ба сифр оварда мешавад.
Duration sinceServerTime(DateTime? when) {
  if (when == null) return Duration.zero;
  final d = DateTime.now().difference(when.toLocal());
  return d.isNegative ? Duration.zero : d;
}
