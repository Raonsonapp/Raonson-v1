import 'dart:async';

/// Хабари «ин мундариҷа ҳазф шуд» ба ҲАМАИ экранҳо.
///
/// ⚠️ Чаро ин лозим шуд.
///
/// Корбар постро аз лента ҳазф мекард — он аз лента мепарид, вале дар
/// профил ва дар explore мемонд. Сабаб: ҳар экран нусхаи ХУДИ
/// рӯйхатро дар хотира нигоҳ медорад ва аз ҳазфи экрани дигар
/// бехабар аст. Танҳо баъди навсозии дастӣ (ё баъди мурдани кэши
/// сервер) он нест мешуд.
///
/// Акнун ҳар экране, ки рӯйхат нигоҳ медорад, ба ин ҷараён обуна
/// мешавад ва мундариҷаи ҳазфшударо ФАВРАН мебарорад.
///
/// Ин ҷои ҳақиқат НЕСТ — ҳақиқат дар сервер аст. Ин танҳо барои он
/// аст, ки экранҳо ҳамдигарро хабардор кунанд.
class ContentEvents {
  ContentEvents._();

  static final _deleted = StreamController<String>.broadcast();

  /// Шиносаҳои ҳазфшуда (пост, reel ё стори).
  static Stream<String> get deleted => _deleted.stream;

  /// Баъди ҲАР ҳазфи муваффақ ҷеғ зада шавад.
  static void notifyDeleted(String id) {
    if (id.isEmpty) return;
    _deleted.add(id);
  }
}
