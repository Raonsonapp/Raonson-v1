import 'package:flutter/widgets.dart';

// ══════════════════════════════════════════════════════════════════
//  Барқарорсозии пурраи барнома — бе пӯшидан ва боз кушодан.
//
//  ⚠️ Чаро ин лозим шуд.
//
//  Ҳангоми гузариш ба аккаунти дигар, барнома то чанд дақиқа
//  маълумоти аккаунти ПЕШТАРАРО нишон медод.
//
//  `AccountManager.switchTo` кэшҳоро тоза мекард — ва ин дуруст буд,
//  вале КОФӢ НЕСТ. Экранҳо аллакай сохта шудаанд ва рӯйхатҳои
//  худро дар ХОТИРА доранд. Тоза кардани кэш ба онҳо намегӯяд, ки
//  аз нав бор кунанд. Пас лента, профил ва ҳалқаи стори ҳамон чизе
//  мемонданд, ки буданд — то даме ки корбар ҳар экранро даст
//  навсозад ё кэши сервер мурад.
//
//  Ҳал: тамоми дарахти виҷетро аз нав месозем. Ин ҳамон чизест, ки
//  барномаро пӯшида боз кушодан медиҳад — вале дар як лаҳза ва бе
//  баромадан аз барнома.
//
//  Ин аз «ҳар экранро як-як хабардор кардан» боэътимодтар аст:
//  экрани нав, ки касе фаромӯш кунад, худ ба худ дуруст кор
//  мекунад, чунки он умуман аз нав сохта мешавад.
// ══════════════════════════════════════════════════════════════════

/// Рақами насли барнома. Ҳар зиёдшавӣ дарахтро аз нав месозад.
final ValueNotifier<int> appGeneration = ValueNotifier<int>(0);

/// Тамоми барномаро аз нав месозад.
///
/// Баъди он `AppState.initialize()` токенро аз нав мехонад ва
/// барнома бо аккаунти ФАЪОЛ барқарор мешавад.
void restartApp() => appGeneration.value++;

/// Решаи барнома, ки ба `restartApp()` гӯш медиҳад.
class AppRestartScope extends StatelessWidget {
  final Widget child;
  const AppRestartScope({super.key, required this.child});

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<int>(
      valueListenable: appGeneration,
      builder: (_, gen, __) => KeyedSubtree(
        // Калиди нав = дарахти нав. Ҳамаи ҳолати кӯҳна партофта
        // мешавад: провайдерҳо, контроллерҳо, рӯйхатҳо, плеерҳо.
        key: ValueKey('app-gen-$gen'),
        child: child,
      ),
    );
  }
}
